#!/usr/bin/env python3
"""Generate anti-aliased VLW fonts (LovyanGFX / TFT_eSPI "smooth fonts") as C arrays.

Usage:  python3 tools/gen_fonts.py            (needs Pillow: pip install pillow)

Fonts used (both SIL Open Font License):
  * Lato           https://fonts.google.com/specimen/Lato
  * FontAwesome 4.7 https://fontawesome.com/v4/  (icons, mapped at their PUA code points)

Output: lib/display/font_data.h  (included only by lib/display/fonts.cpp)
Edit FONTS / ICONS below to add glyphs or sizes, then re-run.
"""
import os
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "lib", "display", "font_data.h")

FONT_DIRS = ["/usr/share/fonts/truetype/lato", "/usr/share/fonts/truetype/font-awesome",
             os.path.join(ROOT, "tools", "fonts")]

LATIN = list(range(0x20, 0x7F)) + [0xA1, 0xB0, 0xB7, 0xBF, 0xC1, 0xC9, 0xCD, 0xD1, 0xD3, 0xDA, 0xDC,
                                   0xE1, 0xE9, 0xED, 0xF1, 0xF3, 0xFA, 0xFC]
DIGITS = [ord(c) for c in " 0123456789:%-.+APM°"]

# FontAwesome 4.7 code points used by the UI (keep in sync with lib/display/icons.h)
ICONS = [
    0xF00C, 0xF00D, 0xF011, 0xF012, 0xF013, 0xF015, 0xF017, 0xF021, 0xF03A, 0xF041,
    0xF043, 0xF04B, 0xF04C, 0xF04D, 0xF053, 0xF054, 0xF05A, 0xF05B, 0xF062, 0xF063,
    0xF067, 0xF068, 0xF071, 0xF073, 0xF076, 0xF077, 0xF078, 0xF07D, 0xF0AC, 0xF0AD,
    0xF0C2, 0xF0C7, 0xF0E2, 0xF0E4, 0xF0E7, 0xF0E9, 0xF0EB, 0xF0ED, 0xF0F3, 0xF0F4,
    0xF185, 0xF186, 0xF1DE, 0xF1EB, 0xF207, 0xF236, 0xF252, 0xF2C9, 0xF2DB, 0xF2DC,
]

# name, file, pixel size, code points
FONTS = [
    ("font_small", "Lato-Semibold.ttf", 16, LATIN),
    ("font_body", "Lato-Semibold.ttf", 21, LATIN),
    ("font_title", "Lato-Bold.ttf", 28, LATIN),
    ("font_big", "Lato-Light.ttf", 70, DIGITS),
    ("font_icon", "fontawesome-webfont.ttf", 22, ICONS),
    ("font_icon_big", "fontawesome-webfont.ttf", 46, ICONS),
]


def find(name):
    for d in FONT_DIRS:
        p = os.path.join(d, name)
        if os.path.exists(p):
            return p
    sys.exit(f"font file not found: {name} (looked in {FONT_DIRS})")


def build_vlw(path, size, codepoints):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    for cp in sorted(set(codepoints)):
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        if cp == 0x20:
            glyphs.append((cp, 0, 0, adv, 0, 0, b""))
            continue
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = r - l, b - t
        if w <= 0 or h <= 0:
            glyphs.append((cp, 0, 0, adv, 0, 0, b""))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
        assert w < 256 and -128 <= l < 128 and adv < 256, f"glyph {cp:#x} too large for VLW"
        glyphs.append((cp, h, w, adv, -t, l, img.tobytes()))

    out = bytearray(struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent))
    for cp, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", cp, h, w, adv, dy, dx, 0)
    for g in glyphs:
        out += g[6]
    return bytes(out)


def main():
    parts = ["// Generated by tools/gen_fonts.py - do not edit by hand.\n#pragma once\n#include <stdint.h>\n"]
    total = 0
    for name, file, size, cps in FONTS:
        data = build_vlw(find(file), size, cps)
        total += len(data)
        rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
        parts.append(f"// {file} @ {size}px, {len(set(cps))} glyphs, {len(data)} bytes\n"
                     f"static const uint8_t {name}[] = {{\n  " + ",\n  ".join(rows) + "\n};\n")
        print(f"{name:14s} {file:26s} {size:3d}px {len(data):7d} bytes")
    with open(OUT, "w") as f:
        f.write("\n".join(parts))
    print(f"total {total} bytes -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
