#!/usr/bin/env python3
"""Small version of the panel's volcano emblem ("ANDES MADE") for the motor board.

It reuses ../blinds-pcb/tools/pcb_silk/emblem.py unchanged: the picture is
rendered with the panel layout, but with the engraving pitch and minimum
line width enlarged by 1/S, then everything is shrunk by S. So the picture
keeps its composition and every final line and gap is still >= 0.16 mm.
The frame and the title are drawn at the final size (the names line is
dropped: too small to print).

Writes tools/emblem_small.json, drawn by tools/silk.py. Same environment as
the panel script:

    uv venv /tmp/emblem-env
    uv pip install -p /tmp/emblem-env numpy scipy tifffile imagecodecs \\
        opencv-python-headless fonttools pillow
    /tmp/emblem-env/bin/python tools/emblem_small.py --dem ~/.cache/dem \\
        --preview /tmp/emblem_small.png
"""
import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / "blinds-pcb" / "tools" / "pcb_silk"))
import emblem as em  # noqa: E402

OUT = HERE / "emblem_small.json"

# final layout, board mm (motor board, top band between the two upper screws)
FX0, FY0, FW = 139.5, 79.9, 21.0
FRAME_R, FRAME_W, FRAME_GAP = 0.8, 0.18, 0.25
TITLE_CAP, TITLE_TRACK = 1.15, 0.35
RULE_W, RULE_GAP = 0.18, 0.7

S = FW / (em.FRAME[2] - em.FRAME[0])            # final / panel scale
FH = (em.FRAME[3] - em.FRAME[1]) * S
TITLE_BASE = FY0 + FH + 0.5 + TITLE_CAP


def setup():
    """Panel geometry, engraving limits enlarged by 1/S."""
    em.MIN = em.MIN / S
    em.PITCH = em.PITCH / S
    em.PX = em.PX * S
    em.FRAME_R, em.FRAME_W, em.FRAME_GAP = FRAME_R / S, FRAME_W / S, FRAME_GAP / S
    em.SX0 = em.FRAME[0] + em.FRAME_W + em.FRAME_GAP
    em.SY0 = em.FRAME[1] + em.FRAME_W + em.FRAME_GAP
    em.SX1 = em.FRAME[2] - em.FRAME_W - em.FRAME_GAP
    em.SY1 = em.FRAME[3] - em.FRAME_W - em.FRAME_GAP
    em.W = int(round((em.SX1 - em.SX0) * em.PX))
    em.H = int(round((em.SY1 - em.SY0) * em.PX))


def shrink(polys):
    def t(p):
        return (round(FX0 + (p[0] - em.FRAME[0]) * S, 4), round(FY0 + (p[1] - em.FRAME[1]) * S, 4))
    return [[[t(p) for p in c] for c in poly] for poly in polys]


def frame_and_title():
    x0, y0, x1, y1 = FX0, FY0, FX0 + FW, FY0 + FH
    w = FRAME_W
    polys = [[em.round_rect(x0, y0, x1, y1, FRAME_R),
              em.round_rect(x0 + w, y0 + w, x1 - w, y1 - w, FRAME_R - w)[::-1]]]
    xc = (x0 + x1) / 2
    title, tx0, tx1 = em.text(em.TITLE, em.TITLE_FONT, TITLE_CAP, TITLE_TRACK, xc, TITLE_BASE)
    ym = TITLE_BASE - TITLE_CAP / 2
    for a, b in ((x0 + 0.5, tx0 - RULE_GAP), (tx1 + RULE_GAP, x1 - 0.5)):
        polys.append([[(a, ym - RULE_W / 2), (b, ym - RULE_W / 2),
                       (b, ym + RULE_W / 2), (a, ym + RULE_W / 2)]])
    return polys + title


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dem", type=Path, required=True, help="folder for the DEM tiles")
    ap.add_argument("--preview", type=Path, help="write a PNG preview here")
    a = ap.parse_args()
    setup()
    xs, ys, Z, SN = em.landscape(a.dem.expanduser())
    ink = em.engrave(*em.render(xs, ys, Z, SN))
    polys = shrink(em.vectorise(ink)) + frame_and_title()
    OUT.write_text(json.dumps({"note": "generated by emblem_small.py, do not edit",
                               "box": [FX0, FY0, FX0 + FW, TITLE_BASE + 0.1],
                               "polys": polys}, separators=(",", ":")))
    print("scale %.3f, frame %.1f x %.2f mm, %d polygons -> %s" % (S, FW, FH, len(polys), OUT))
    if a.preview:
        em.FRAME = (FX0, FY0, FX0 + FW, FY0 + FH)
        from PIL import Image, ImageChops, ImageDraw
        sc, bx0, by0 = 60, FX0 - 0.5, FY0 - 0.5
        size = (int((FW + 1) * sc), int((TITLE_BASE + 0.6 - by0) * sc))
        img = Image.new("L", size, 0)
        for poly in polys:
            one = Image.new("L", size, 0)
            d = ImageDraw.Draw(one)
            for i, c in enumerate(poly):
                d.polygon([((x - bx0) * sc, (y - by0) * sc) for x, y in c], fill=0 if i else 255)
            img = ImageChops.lighter(img, one)
        img.save(a.preview)


if __name__ == "__main__":
    main()
